import type { ExactAnalysis } from '../exact-analysis/analysis';
import type { SensitivityReport } from '../exact-analysis/sensitivity';
import type { ComparisonRow, SimulationReport } from '../simulation/report';

export interface ReportInputs {
  readonly analysis: ExactAnalysis & { readonly sensitivity?: SensitivityReport | null };
  readonly simulations: readonly (SimulationReport & { readonly comparison?: readonly ComparisonRow[] | null })[];
  readonly generatedAt: string;
}

const pct = (x: number, d = 4) => `${(x * 100).toFixed(d)}%`;
const num = (x: number, d = 4) => (Number.isFinite(x) ? x.toLocaleString('en-US', { maximumFractionDigits: d }) : String(x));
const sci = (x: number, d = 3) => (x === 0 ? '0' : x.toExponential(d));
const oneIn = (p: number) => (p > 0 ? `1 in ${num(1 / p, p > 0.01 ? 2 : 0)}` : 'n/a');
const prob = (p: number) => (p >= 1e-3 ? pct(p, 3) : sci(p));

function table(header: readonly string[], rows: readonly (readonly (string | number)[])[]): string {
  const line = (cells: readonly (string | number)[]) => `| ${cells.map((c) => String(c).replace(/\|/g, '\\|')).join(' | ')} |`;
  return [line(header), `|${header.map(() => '---').join('|')}|`, ...rows.map(line)].join('\n');
}

/** Renders docs/RTP_REPORT.md from computed results only. */
export function renderRtpReport({ analysis: a, simulations, generatedAt }: ReportInputs): string {
  const out: string[] = [];
  const p = (s = '') => out.push(s);

  p(`# RTP and Mathematical Report: ${a.game.name} ${a.game.version}`);
  p();
  p('> **Status: play-money prototype.** This report documents the mathematical model as configured. It is not a certification, has not been reviewed by an independent test laboratory, and does not establish suitability for real-money use in any jurisdiction.');
  p();
  p(table(['Item', 'Value'], [
    ['Configuration hash (SHA-256 of canonical JSON)', `\`${a.game.configHash}\``],
    ['Exact analysis generated', a.generatedAt],
    ['Report generated', generatedAt],
    ['Grid', `${a.configSummary.reels} reels x ${a.configSummary.rows} rows, ${a.configSummary.paylines} fixed paylines`],
    ['Reel strip lengths', Object.entries(a.configSummary.reelLengths).map(([k, v]) => `${k}: ${v.join(' / ')}`).join('; ')],
    ['Round win cap', a.configSummary.maxWinMultiplier === null ? 'none' : `${num(a.configSummary.maxWinMultiplier)}x total bet`],
    ['Free spins limit per feature', a.configSummary.freeSpinsMaxTotal === null ? 'unlimited' : `${a.configSummary.freeSpinsMaxTotal} spins`],
  ]));
  p();
  p('All values in this report are regenerated by `npm run analyze`, the simulation scripts and `npm run report`; none are typed in by hand. "Theoretical" values come from exact enumeration; "simulated" values are Monte Carlo estimates and carry sampling error.');
  p();

  p('## 1. Definitions');
  p();
  for (const [k, v] of Object.entries(a.definitions)) p(`- **${k}**: ${v}`);
  p();

  p('## 2. Headline results (theoretical, exact)');
  p();
  p(table(['Metric', 'Value'], [
    ['Total RTP (per unit of base-game stake)', pct(a.rtp.total)],
    ['Design target', pct(a.rtp.target, 2)],
    ['Deviation from target', `${(a.rtp.deviationFromTarget * 100).toFixed(4)} percentage points`],
    ['Base-game RTP (line wins + scatter wins of paid spins)', pct(a.rtp.base)],
    ['  of which line wins', pct(a.rtp.baseLine)],
    ['  of which scatter wins', pct(a.rtp.baseScatter)],
    ['Free-spins feature contribution', pct(a.rtp.feature)],
    ['Expected payout per unit stake', num(a.rtp.expectedPayoutPerUnitStake, 6)],
    ['Expected net return per unit stake', num(a.rtp.expectedNetPerUnitStake, 6)],
    ['RTP removed by the win cap', Math.abs(a.rtp.capEffect) < 1e-9 ? `negligible (${sci(a.rtp.capEffect, 1)}, at the level of floating-point noise)` : sci(a.rtp.capEffect)],
    ['Hit frequency (round pays > 0)', pct(a.round.hitFrequency, 3)],
    ['Probability of a winning payline (paid spin)', pct(a.baseGame.lineWinProbability, 3)],
    ['Probability of a net-positive round (pays > stake)', pct(a.round.probabilityNetPositive, 3)],
    ['Probability a round pays something but less than the stake', pct(a.round.probabilityWinBelowStake, 3)],
    ['Probability a round returns exactly the stake', pct(a.round.probabilityReturnsStake, 3)],
    ['Free-spins trigger probability', `${prob(a.feature.triggerProbability)} (${oneIn(a.feature.triggerProbability)} paid spins)`],
    ['Expected free spins per trigger', num(a.feature.expectedFreeSpinsPerTrigger, 4)],
    ['Expected feature win', `${num(a.feature.expectedWin, 3)}x total bet`],
    ['Standard deviation of round return', `${num(a.round.sd, 4)} per unit stake (variance ${num(a.round.variance, 3)})`],
    ['Volatility class (documented heuristic)', a.volatility.classification],
    ['Largest base-spin win', `${num(a.round.maxBaseSpinWin)}x total bet`],
    ['Largest free-spin win', `${num(a.round.maxFreeSpinWin)}x total bet`],
    ['Largest round payout (upper bound under the rules)', `${num(a.round.maxPossibleWinUpperBound)}x total bet`],
  ]));
  p();

  p('## 3. Method');
  p();
  p(a.method.summary);
  p();
  p(table(['Item', 'Value'], [
    ['Base-game stop combinations enumerated', num(a.method.baseCombinations)],
    ['Free-spin stop combinations enumerated', num(a.method.freeCombinations)],
    ['Enumeration time (base / free)', `${(a.method.enumerationMs.base / 1000).toFixed(1)} s / ${(a.method.enumerationMs.free / 1000).toFixed(1)} s`],
    ['Feature Markov-chain states', num(a.method.featureStates)],
    ['FFT size / transforms', `${num(a.method.fftSize)} / ${num(a.method.fftCount)}`],
    ['Payout grid', `0..${num(a.method.horizonUnits)} line-bet units${a.method.capped ? ' (= round cap)' : ' (analysis horizon)'}`],
    ['Total probability mass error', sci(a.method.totalMassError)],
    ['Numerical floor for tail probabilities', sci(a.method.numericalFloor, 1)],
    ['Marginal vs enumeration mean, max abs difference', sci(a.crossChecks.maxAbsDifference)],
  ]));
  p();
  p(`Probabilities smaller than the numerical floor (${sci(a.method.numericalFloor, 1)}) are below the resolution of the FFT-based distribution and are reported as "below floor" rather than as a number.`);
  p();

  p('## 4. RTP contribution by symbol');
  p();
  const syms = new Map<string, { base: number; free: number }>();
  for (const s of a.baseGame.symbolContributions) syms.set(s.symbol, { base: s.rtp, free: 0 });
  const trig = a.feature.triggerProbability * a.feature.expectedFreeSpinsPerTrigger;
  for (const s of a.freeGame.symbolContributions) {
    const e = syms.get(s.symbol) ?? { base: 0, free: 0 };
    e.free = s.rtp * trig;
    syms.set(s.symbol, e);
  }
  p('Free-spin contributions are per unit of base-game stake: per-free-spin RTP x expected free spins per paid spin (uncapped; the cap effect is negligible here).');
  p();
  p(table(['Symbol', 'Base game', 'Free spins', 'Total'], [
    ...[...syms.entries()].map(([k, v]) => [k, pct(v.base, 3), pct(v.free, 3), pct(v.base + v.free, 3)]),
    ['Scatter pays', pct(a.baseGame.scatterContribution, 3), pct(a.freeGame.scatterContribution * trig, 3), pct(a.baseGame.scatterContribution + a.freeGame.scatterContribution * trig, 3)],
  ]));
  p();

  p('## 5. Paytable combination probabilities (base game)');
  p();
  p('Probability that one given payline pays exactly this combination on a paid spin (highest win per line only), averaged over the 20 paylines.');
  p();
  p(table(['Symbol', 'Count', 'Pay (x line bet)', 'P per line', 'Odds per line', 'RTP contribution'],
    a.baseGame.lineCombinations.map((c) => [c.symbol, c.count, c.pay, sci(c.probabilityPerLine), `1 in ${num(c.oneInPerLine, 0)}`, pct(c.rtpContribution, 4)])));
  p();
  p('Simultaneous winning paylines on a paid spin:');
  p();
  p(table(['Winning paylines', 'Probability'], a.baseGame.winningLinesPmf.map((r) => [r.lines, prob(r.probability)])));
  p();
  p('Visible scatter count on a paid spin:');
  p();
  p(table(['Scatters', 'Probability', 'Free spins awarded'], a.baseGame.scatterCountPmf.map((r) => [r.scatters, prob(r.probability), a.feature.triggerByScatterCount.find((t) => t.scatters === r.scatters)?.award ?? 0])));
  p();

  p('## 6. Free spins');
  p();
  p(table(['Metric', 'Value'], [
    ['Trigger probability per paid spin', `${prob(a.feature.triggerProbability)} (${oneIn(a.feature.triggerProbability)})`],
    ['Expected paid spins between triggers', num(a.feature.expectedBaseSpinsBetweenTriggers, 2)],
    ['Expected free spins per trigger (incl. retriggers)', num(a.feature.expectedFreeSpinsPerTrigger, 4)],
    ['Retrigger probability per free spin', prob(a.freeGame.retriggerProbabilityPerSpin)],
    ['Probability a feature retriggers at least once', prob(a.feature.probabilityAnyRetrigger)],
    ['Expected retriggers per feature', num(a.feature.expectedRetriggersPerFeature, 5)],
    ['Expected free-spin win per free spin', `${num(a.freeGame.expectedWin, 4)}x total bet`],
    ['Free-spin hit frequency', pct(a.freeGame.hitFrequency, 3)],
    ['Expected free-spins payout per trigger (after the round cap)', `${num(a.feature.expectedWin, 4)}x total bet`],
    ['Expected feature win, uncapped (Wald identity)', `${num(a.feature.expectedWinUncapped, 4)}x total bet`],
    ['Expected free spins played per trigger (cap-aware)', num(a.feature.expectedFreeSpinsPlayedPerTrigger, 4)],
    ['Stand-alone feature win: mean / SD', `${num(a.feature.standaloneMeanWin, 4)}x / ${num(a.feature.sdWin, 3)}x total bet`],
    ['Stand-alone feature win quantiles (x bet)', Object.entries(a.feature.quantiles).map(([k, v]) => `${k}: ${v}`).join(', ')],
  ]));
  p();
  p(table(['Free spins played in the feature', 'Probability'], a.feature.freeSpinsPmf.map((r) => [r.spins, prob(r.probability)])));
  p();
  p('The stand-alone feature distribution is the win of the free spins alone (capped at the round cap), conditional on a trigger.');
  p();
  p(table(['Stand-alone feature win at least', 'Probability', 'Odds'], a.feature.probabilityWinAtLeast.map((r) => [`${num(r.multiplier)}x`, r.belowNumericalFloor ? 'below floor' : prob(r.probability), r.oneIn ? `1 in ${num(r.oneIn, 0)}` : 'n/a'])));
  p();

  p('## 7. Payout distribution and volatility');
  p();
  p(table(['Metric', 'Value'], [
    ['Mean round return per unit stake', num(a.round.mean, 6)],
    ['Variance', num(a.round.variance, 4)],
    ['Standard deviation', num(a.round.sd, 4)],
    ['Coefficient of variation', num(a.round.coefficientOfVariation, 3)],
    ['Skewness', num(a.round.skewness, 2)],
    ['Excess kurtosis', num(a.round.excessKurtosis, 1)],
    ['Quantiles of round payout (x bet)', Object.entries(a.round.quantiles).map(([k, v]) => `${k}: ${v}`).join(', ')],
  ]));
  p();
  p(table(['Round payout band (x total bet)', 'Probability', 'RTP contribution'], a.round.bands.map((b) => [b.label, b.probability === 0 ? '0 or below floor' : prob(b.probability), pct(b.rtpContribution, 3)])));
  p();
  p(`**Volatility.** ${a.volatility.scale} With SD ${num(a.round.sd, 3)} this configuration is classified **${a.volatility.classification}**.`);
  p();
  p(table(['Share of RTP from rounds paying at least', 'Share'], a.volatility.rtpShareFromRoundsAtLeast.map((r) => [`${num(r.multiplier)}x bet`, pct(r.share, 3)])));
  p();
  p(table(['Session length (paid spins)', 'SD of session RTP (CLT)'], a.volatility.sessionRtpSd.map((r) => [num(r.rounds), `${(r.sd * 100).toFixed(2)} pts`])));
  p();
  for (const c of a.volatility.caveats) p(`- ${c}`);
  p();

  p('## 8. High-payout events');
  p();
  p(table(['Round pays at least', 'Probability', 'Odds', 'Paid spins needed to estimate within +/-10% (95%)'],
    a.round.thresholds.map((t) => [`${num(t.multiplier)}x bet`, t.belowNumericalFloor ? 'below floor' : prob(t.probability), t.oneIn ? `1 in ${num(t.oneIn, 0)}` : 'n/a', t.roundsFor10PctPrecision ? sci(t.roundsFor10PctPrecision, 2) : 'n/a'])));
  p();
  p(`Win cap: ${a.configSummary.maxWinMultiplier === null ? 'not configured.' : `${num(a.configSummary.maxWinMultiplier)}x total bet per round. P(round reaches the cap) ${a.round.capProbabilityBelowFloor ? `is below the numerical floor (< ${sci(a.method.numericalFloor, 1)})` : `= ${sci(a.round.capProbability)}`}. The largest single free-spin win is ${num(a.round.maxFreeSpinWin)}x, so the cap can only be reached by several near-maximal free spins in one feature.`}`);
  p();
  p('**Why millions of simulated spins are not enough for rare events.** The relative standard error of an estimated probability p from n independent rounds is about sqrt((1 - p) / (n p)). An event with p = 1e-6 is expected about 10 times in 10 million rounds, giving a relative error of roughly 30%; for p below 1e-8 a 10-million-round simulation will usually observe no event at all. Rare-event probabilities in this report therefore come from exact enumeration; the simulations only confirm the frequent quantities.');
  p();

  p('## 9. Consecutive losing rounds');
  p();
  p(a.losingStreaks.note);
  p();
  p(table(['Run length n', 'P(at least n no-win rounds in a row)', 'P(at least n net-losing rounds in a row)'],
    a.losingStreaks.noWinStreakAtLeast.map((r, i) => [r.rounds, prob(r.probability), prob(a.losingStreaks.netLosingStreakAtLeast[i]!.probability)])));
  p();
  p(`P(no-win round) = ${pct(a.losingStreaks.probabilityNoWinRound, 3)}; expected no-win rounds before a win = ${num(a.losingStreaks.expectedNoWinRoundsBeforeWin, 4)}. P(net-losing round) = ${pct(a.losingStreaks.probabilityNetLosingRound, 3)}.`);
  p();

  p('## 10. Simulation results and comparison with theory');
  p();
  if (simulations.length === 0) p('No simulation results were found. Run `npm run simulate:100k`, `simulate:1m` and `simulate:10m`.');
  for (const s of simulations) {
    p(`### ${num(s.totals.rounds)} paid spins (${s.meta.rngKind === 'seeded' ? `seed "${s.meta.seed}"` : 'crypto RNG'})`);
    p();
    p(table(['Item', 'Value'], [
      ['Configuration hash matches analysis', s.game.configHash === a.game.configHash ? 'yes' : '**NO - results are for a different configuration**'],
      ['Free spins played', num(s.totals.freeSpins)],
      ['Total stake / total payout (credits at line bet 1)', `${num(s.totals.totalStake)} / ${num(s.totals.totalPayout)}`],
      ['Simulated RTP', `${pct(s.rtp.estimate)} (95% CI ${pct(s.rtp.ci95.low)} to ${pct(s.rtp.ci95.high)})`],
      ['Batch-means 95% CI', `${pct(s.rtp.batchMeansCi95.low)} to ${pct(s.rtp.batchMeansCi95.high)} (${s.rtp.batchMeansCi95.batches} batches)`],
      ['Observed SD of round return', num(s.roundPayout.sd, 4)],
      ['Largest round win observed', `${num(s.extremes.maxRoundWin)}x bet`],
      ['Longest no-win streak observed', num(s.losingStreaks.longest)],
      ['Runtime', `${(s.meta.elapsedMs / 1000).toFixed(1)} s on ${s.meta.workers} worker thread(s) (${num(s.meta.roundsPerSecond)} rounds/s)`],
    ]));
    p();
    if (s.comparison && s.comparison.length > 0) {
      p(table(['Metric', 'Theoretical', 'Simulated', '95% CI', 'z', 'Events', 'Theory inside CI'],
        s.comparison.map((c) => [c.metric, c.theoretical < 1e-3 ? sci(c.theoretical) : num(c.theoretical, 6), c.simulated < 1e-3 ? sci(c.simulated) : num(c.simulated, 6), `${c.ci95Low < 1e-3 ? sci(c.ci95Low, 2) : num(c.ci95Low, 5)} .. ${c.ci95High < 1e-3 ? sci(c.ci95High, 2) : num(c.ci95High, 5)}`, c.z.toFixed(2), c.events ?? '-', `${c.withinCi95 ? 'yes' : 'no'}${c.reliable ? '' : ' (few events)'}`])));
      p();
      const outside = s.comparison.filter((c) => !c.withinCi95);
      const big = s.comparison.filter((c) => Math.abs(c.z) > 3);
      p(`${s.comparison.length} metrics compared; ${outside.length} theoretical value(s) fall outside the simulated 95% interval${outside.length ? ` (${outside.map((c) => c.metric).join('; ')})` : ''}. With ${s.comparison.length} correlated comparisons, about ${(s.comparison.length * 0.05).toFixed(1)} would be expected outside by chance. ${big.length === 0 ? 'No discrepancy exceeds |z| = 3.' : `Discrepancies with |z| > 3: ${big.map((c) => c.metric).join('; ')} - investigate.`}`);
      p();
    }
    if (s.warnings.length) {
      p('<details><summary>Sample-size warnings</summary>');
      p();
      for (const w of s.warnings) p(`- ${w}`);
      p();
      p('</details>');
      p();
    }
  }

  const sens = a.sensitivity;
  if (sens) {
    p('## 11. Sensitivity and candidate parameter changes');
    p();
    p(`Current exact (uncapped) RTP ${pct(sens.currentRtp)} vs target ${pct(sens.target, 2)}: deviation ${(sens.deviation * 100).toFixed(4)} points. ${Math.abs(sens.deviation) <= 0.0005 ? 'The configuration is within 0.05 points of the target; the candidates below are listed for future tuning only.' : 'The configuration misses the target; the candidates below are concrete single-parameter edits ranked by closeness to the target.'} Each candidate must be applied to the configuration and re-verified with the full analysis; nothing is ever adjusted at runtime.`);
    p();
    p(table(['Single reel-stop change', 'RTP after', 'Change (pts)'], sens.closestToTarget.slice(0, 10).map((c) => [c.description, pct(c.rtpAfter), (c.delta * 100).toFixed(4)])));
    p();
    p(table(['Paytable change (about +10%)', 'RTP after', 'Change (pts)'], sens.paytable.slice(0, 12).map((c) => [c.description, pct(c.rtpAfter), (c.delta * 100).toFixed(4)])));
    p();
  }

  p('## 12. Reproducing these results');
  p();
  p('```bash');
  p('npm ci');
  p('npm run analyze          # exact analysis -> reports/analysis.json (+ CSV tables)');
  p('npm run simulate:100k    # seeded presets -> reports/simulation-*.json/.csv');
  p('npm run simulate:1m');
  p('npm run simulate:10m');
  p('npm run report           # regenerates this file and reports/comparison-*.csv');
  p('```');
  p();
  p('Seeded simulations are bit-for-bit reproducible for a given seed, chunk size and configuration, independent of the number of worker threads. Use `--crypto` for a non-reproducible run with the cryptographic RNG.');
  p();
  p('## 13. Limitations');
  p();
  p('- Results describe the configuration with the hash above only. Any change to the configuration invalidates them (the test suite enforces this).');
  p('- The exact analysis relies on floating-point arithmetic; probabilities below the stated numerical floor are not resolved.');
  p('- Simulation confidence intervals use the normal approximation for round returns; for heavy-tailed returns and short runs they are approximate.');
  p('- The prototype RNG and outcome generation run on the client. Real-money operation would require a server-side, independently certified RNG and outcome service (see docs/REGULATORY_READINESS.md).');
  p();
  return out.join('\n');
}
