/**
 * Builds the whole game into ONE self-contained HTML file and writes it to the
 * repository root as index.html. It runs from a double-click (file://) or from any
 * static web host: scripts, styles, the pixel font, the symbol art, the simulation
 * worker and the favicon are all inlined; nothing is loaded from the network.
 *
 * Usage: npm run build:standalone
 */
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join } from 'node:path';
import { build } from 'vite';

const OUT = 'index.html';

await build({ configFile: 'vite.config.ts', mode: 'standalone', logLevel: 'warn' });
let html = readFileSync('dist-standalone/index.html', 'utf8');

// Local references the HTML itself (not the inline scripts) still makes.
const localRefs = () => {
  const markup = html.replace(/(<script\b[^>]*>)[\s\S]*?<\/script>/gi, '$1</script>');
  return [...markup.matchAll(/<(?:script|link|img|source)\b[^>]*\b(?:src|href)\s*=\s*["']([^"']+)["']/gi)]
    .map((m) => m[1]!)
    .filter((u) => !u.startsWith('data:') && !u.startsWith('#'));
};

// Vite emits the favicon as a file; inline it (and anything similar) as a data URI.
const MIME: Record<string, string> = { '.svg': 'image/svg+xml', '.png': 'image/png', '.ico': 'image/x-icon' };
for (const ref of localRefs()) {
  const file = join('dist-standalone', ref);
  const mime = MIME[extname(ref)];
  if (!mime || !existsSync(file)) continue;
  const uri = `data:${mime};base64,${readFileSync(file).toString('base64')}`;
  html = html.split(`"${ref}"`).join(`"${uri}"`);
}

const refs = localRefs();
if (refs.length > 0) {
  console.error(`The standalone build still references external files: ${refs.join(', ')}`);
  process.exit(1);
}

const banner =
  '<!-- Pixel-Pauker: standalone play-money build (no real money). Generated by "npm run build:standalone" from the sources in this repository - do not edit by hand. -->';
html = html.replace(/<head>/i, `<head>\n    ${banner}`);
writeFileSync(OUT, html);
const kb = statSync(OUT).size / 1024;
console.log(`Wrote ${OUT} (${kb.toFixed(0)} KiB, self-contained)`);
